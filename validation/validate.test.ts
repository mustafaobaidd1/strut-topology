/**
 * Slow validation suite: `npm run validate`. Writes docs/validation-results.md.
 * The fast subset of these checks also runs as unit tests in src/.
 */
import { writeFileSync } from 'node:fs';
import { cpus } from 'node:os';
import { afterAll, describe, expect, it } from 'vitest';
import {
  cantilever,
  eulerBernoulliTip,
  exactCantilever,
  solvePrescribed,
  timoshenkoTip,
} from '../src/lib/fem/analysis';
import { createGrid, nodeXY } from '../src/lib/fem/grid';
import type { SolverKind } from '../src/lib/fem/solver';
import { mirrorMap, Optimizer, type OptimizerParams } from '../src/lib/opt/optimizer';
import { cantileverMid, mbbHalf, symmetricBridge } from '../src/lib/opt/testProblems';
import { runTop88, type FilterType88 } from '../src/lib/opt/top88';
import { makePreset } from '../src/lib/problem/presets';
import { resolveProblem } from '../src/lib/problem/resolve';
import { rng } from '../src/lib/testing/dense';

const report: string[] = [];
const line = (s = '') => report.push(s);
const ms = (t0: number) => performance.now() - t0;

afterAll(() => {
  const header = [
    '# Strut — validation results',
    '',
    `Generated by \`npm run validate\` on ${new Date().toISOString().slice(0, 10)}, Node ${process.version}, ${cpus()[0]?.model ?? 'unknown CPU'}.`,
    'Timings are wall-clock on that machine and only indicative.',
    '',
  ];
  writeFileSync('docs/validation-results.md', [...header, ...report, ''].join('\n'));
});

describe('validation', () => {
  it('patch test: uniform strain reproduced exactly', () => {
    line('## Patch test');
    line('');
    line(
      'Linear displacement field prescribed on the boundary of an 8 × 4 mesh; interior nodes must follow it exactly.',
    );
    line('');
    line('| Solver | Max nodal error |');
    line('|---|---|');
    for (const kind of ['direct', 'mgcg', 'jacobi'] as SolverKind[]) {
      const grid = createGrid(8, 4);
      const fixed = new Uint8Array(grid.nDofs);
      const prescribed = new Float64Array(grid.nDofs);
      const f = (x: number, y: number): [number, number] => [
        0.01 + 0.002 * x - 0.003 * y,
        -0.02 + 0.004 * x + 0.001 * y,
      ];
      for (let n = 0; n < grid.nNodes; n++) {
        const [x, y] = nodeXY(grid, n);
        if (x === 0 || x === 8 || y === 0 || y === 4) {
          const [u, v] = f(x, y);
          fixed[2 * n] = fixed[2 * n + 1] = 1;
          prescribed[2 * n] = u;
          prescribed[2 * n + 1] = v;
        }
      }
      const u = solvePrescribed(
        { grid, fixed, prescribed, force: new Float64Array(grid.nDofs) },
        kind,
      );
      let err = 0;
      for (let n = 0; n < grid.nNodes; n++) {
        const [x, y] = nodeXY(grid, n);
        const [ue, ve] = f(x, y);
        err = Math.max(err, Math.abs(u[2 * n] - ue), Math.abs(u[2 * n + 1] - ve));
      }
      line(`| ${kind} | ${err.toExponential(1)} |`);
      expect(err).toBeLessThan(1e-12);
    }
    line('');
  });

  it('cantilever vs Timoshenko beam theory and the elasticity solution', () => {
    const ratio = 8;
    const ref = timoshenkoTip(ratio, 1);
    line('## Cantilever, L/H = 8, end shear P = 1 (E = 1, ν = 0.3)');
    line('');
    line(
      `Beam theory: Euler–Bernoulli δ = ${eulerBernoulliTip(ratio, 1).toFixed(2)}, Timoshenko (κ = 5/6) δ = ${ref.toFixed(2)}.`,
    );
    line('');
    line(
      '| Elements through depth | Mesh | Tip deflection, clamped root | Error vs Timoshenko | Max displacement error vs elasticity solution (exact root data) | Observed order |',
    );
    line('|---|---|---|---|---|---|');
    let prev = NaN;
    for (const nely of [2, 4, 8, 16, 32, 64]) {
      const r = cantilever(nely, ratio, 'clamped');
      const e = cantilever(nely, ratio, 'exact');
      const exact = exactCantilever(ratio * nely, nely);
      let maxErr = 0;
      let maxRef = 0;
      for (let n = 0; n < e.grid.nNodes; n++) {
        const [x, yt] = nodeXY(e.grid, n);
        const [ue, ve] = exact(x, yt - nely / 2);
        maxErr = Math.max(maxErr, Math.hypot(e.u[2 * n] - ue, e.u[2 * n + 1] - ve));
        maxRef = Math.max(maxRef, Math.hypot(ue, ve));
      }
      const rel = maxErr / maxRef;
      const order = Number.isFinite(prev) ? Math.log2(prev / rel).toFixed(2) : '–';
      prev = rel;
      line(
        `| ${nely} | ${ratio * nely} × ${nely} | ${r.tipDeflection.toFixed(2)} | ${(((r.tipDeflection - ref) / ref) * 100).toFixed(2)} % | ${(rel * 100).toFixed(3)} % | ${order} |`,
      );
    }
    line('');
    line(
      'The clamped root also stops the Poisson contraction at the wall, so the converged clamped result sits about 0.24 % below beam theory; with root displacements taken from the elasticity solution the error falls at second order.',
    );
    line('');
  }, 120_000);

  it('compliance gradient vs central finite differences', () => {
    line('## Compliance gradient vs central differences');
    line('');
    line('16 × 8 cantilever, random design in [0.2, 0.9], direct solver, step h = 1e-4.');
    line('');
    line('| Configuration | Max relative error over 6 elements |');
    line('|---|---|');
    const cases: [string, Partial<OptimizerParams>, number, boolean][] = [
      ['density filter', { projection: false }, 1, false],
      ['density filter + projection, β = 4', { projection: true }, 4, false],
      ['projection β = 2 + passive solid and void', { projection: true }, 2, true],
    ];
    for (const [name, params, beta, passive] of cases) {
      const problem = cantileverMid(16, 8);
      if (passive) {
        problem.passive[26] = 1;
        problem.passive[86] = -1;
      }
      const opt = new Optimizer(problem, { solver: 'direct', ...params });
      opt.beta = beta;
      const rand = rng(21);
      const x0 = Float64Array.from({ length: opt.grid.nEl }, () => 0.2 + 0.7 * rand());
      opt.setDesign(x0);
      const analytic = Float64Array.from(opt.analyse().dc);
      let worst = 0;
      for (const e of [0, 17, 45, 64, 99, 127]) {
        if (problem.passive[e] !== 0) continue;
        const h = 1e-4;
        const xp = Float64Array.from(x0);
        xp[e] += h;
        opt.setDesign(xp);
        const cp = opt.analyse().compliance;
        const xm = Float64Array.from(x0);
        xm[e] -= h;
        opt.setDesign(xm);
        const cm = opt.analyse().compliance;
        const fd = (cp - cm) / (2 * h);
        worst = Math.max(worst, Math.abs(fd - analytic[e]) / Math.abs(fd));
      }
      line(`| ${name} | ${worst.toExponential(1)} |`);
      expect(worst).toBeLessThan(1e-5);
    }
    line('');
  });

  it('88-line reference values (Andreassen et al. 2011, Fig. 3 and 5)', () => {
    line('## 88-line code reproduced');
    line('');
    line(
      'Half MBB beam, volume fraction 0.5, penalty 3, stop when the change drops to 0.01, direct solver. rmin = 0.04 · nelx (0.03 · nelx for the Heaviside variant), as in the paper.',
    );
    line('');
    line(
      '| Mesh | Filter | rmin | Published c | This port | Iterations | First-iteration c | Time |',
    );
    line('|---|---|---|---|---|---|---|---|');
    const runs: [number, number, number, FilterType88, number][] = [
      [60, 20, 2.4, 1, 216.81],
      [60, 20, 2.4, 2, 233.71],
      [60, 20, 1.8, 3, 189.14],
      [150, 50, 6, 1, 219.52],
      [150, 50, 6, 2, 235.73],
    ];
    const names: Record<FilterType88, string> = {
      1: 'sensitivity (ft 1)',
      2: 'density (ft 2)',
      3: 'Heaviside (ft 3)',
    };
    for (const [nx, ny, rmin, ft, published] of runs) {
      const t0 = performance.now();
      const { lines } = runTop88(nx, ny, 0.5, 3, rmin, ft, 3000, 'direct');
      const last = lines[lines.length - 1];
      line(
        `| ${nx} × ${ny} | ${names[ft]} | ${rmin} | ${published.toFixed(2)} | ${last.c.toFixed(4)} | ${lines.length} | ${lines[0].c.toFixed(4)} | ${(ms(t0) / 1000).toFixed(1)} s |`,
      );
      expect(Number(last.c.toFixed(2))).toBeCloseTo(published, 2);
    }
    line('');
  }, 900_000);

  it('interactive engine in the reference settings', () => {
    line('## Interactive engine (MGCG + Illinois λ search) vs the port');
    line('');
    line(
      'Same MBB 60 × 20 problem with the density filter, rmin 2.4, run by the interactive optimiser (multigrid CG to 10⁻⁶, bracketed λ search) with the 0.01 change rule only.',
    );
    line('');
    const opt = new Optimizer(mbbHalf(60, 20), {
      volfrac: 0.5,
      penal: 3,
      rmin: 2.4,
      projection: false,
      stallTol: 0,
      maxIter: 2000,
    });
    let r = opt.step();
    while (!r.converged && opt.runIteration < 2000) r = opt.step();
    line(
      `Final compliance ${r.compliance.toFixed(4)} after ${opt.runIteration} iterations (published 233.71; the paper-exact port gives 233.7146).`,
    );
    line('');
    expect(Math.abs(r.compliance - 233.71) / 233.71).toBeLessThan(0.01);
  }, 300_000);

  it('symmetry and solver performance', () => {
    line('## Symmetry');
    line('');
    const asym = (x: Float64Array, nx: number, ny: number) => {
      const m = mirrorMap(nx, ny);
      let a = 0;
      for (let e = 0; e < x.length; e++) a = Math.max(a, Math.abs(x[e] - x[m[e]]));
      return a;
    };
    for (const solver of ['direct', 'mgcg'] as SolverKind[]) {
      const o = new Optimizer(symmetricBridge(96, 32), { solver, volfrac: 0.3 });
      for (let k = 0; k < 100; k++) o.step();
      line(
        `Symmetric bridge 96 × 32, symmetry not imposed, 100 iterations, ${solver}: max |ρ − mirror(ρ)| = ${asym(o.xPhys, 96, 32).toExponential(1)}.`,
      );
    }
    line('');
    line('## Solver cost per optimisation iteration (bridge preset, projection on)');
    line('');
    line('| Mesh | Elements | Multigrid levels | Mean CG iterations | Mean time per iteration |');
    line('|---|---|---|---|---|');
    const pr = makePreset('bridge');
    for (const nely of [32, 48, 64, 96, 128]) {
      const gp = resolveProblem(pr.problem, nely);
      const o = new Optimizer(gp, {
        volfrac: pr.volfrac,
        rmin: (pr.rmin48 * nely) / 48,
        projection: true,
      });
      const n = nely >= 96 ? 15 : 40;
      let cg = 0;
      const t0 = performance.now();
      for (let k = 0; k < n; k++) cg += o.step().solve.iterations;
      line(
        `| ${gp.nelx} × ${gp.nely} | ${(gp.nelx * gp.nely).toLocaleString('en')} | ${o.solverLevels} | ${(cg / n).toFixed(1)} | ${(ms(t0) / n).toFixed(0)} ms |`,
      );
    }
    line('');
  }, 600_000);
});
